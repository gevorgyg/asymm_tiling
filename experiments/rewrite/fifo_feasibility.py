"""fifo_feasibility: when is a PRNG-FIFO worth it, given the device?

B-stationary matmul with B either loaded from memory or generated by the
FIFO, on the same tile grid. Two views from the same runs:

  * best vs best: each side takes its best (TM, TN); speedup = best memory
    cycles / best FIFO cycles, against the generator speed gamma. Where it
    crosses 1 is the break-even gamma*. This is the device question.
  * fixed tile (TN = TN_FIXED): cycles/MAC against the L1 fill fraction f,
    with both predicted L1 cliffs drawn. This explains where the win comes
    from.

Dimensionless knobs (see the README this script writes):
  rho    = B_P / A_P                      precision ratio, A_P fixed at 8
  gamma  = gc * (LINE / B_P) / mem        generate a line of B / fetch it
  lambda = mem / l1                       DRAM latency in L1 hits
  f      = TM * A_P * (K + TN) / L1       A band + C tile over L1

run:  .venv/bin/python experiments/rewrite/fifo_feasibility.py
"""

from __future__ import annotations

import math
from dataclasses import replace
from itertools import product

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from harness import Params, out_dir, run_many  # noqa: E402

NAME = "fifo_feasibility"

# fixed
M, N, K = 192, 256, 128
A_P = 8                      # bytes per A and C element
LINE = 64
L1 = 64 * 1024
L1_CYC = 4                   # the time unit
TN_FIXED = 16                # fixed-tile view
MNK = M * N * K

# swept
TMS = tuple(range(4, 97, 4))
TNS = (8, 16, 32, 64)
RHOS = (1, 0.5, 0.25, 0.125)             # B_P = 8, 4, 2, 1
LAMBDAS = (45, 100)                      # mem = 180, 400
GAMMAS = (0, 0.25, 0.5, 1, 2, 4, 8)

CYC = "Simulation: Total cycles"
MISS = "CacheUnit: L1 misses"
STALL = "PrngFifo: stall_cycles"


def b_bytes(rho: float) -> int:
    return int(round(rho * A_P))


def gc_of(gamma: float, mem: int, rho: float) -> int:
    """gamma = gc * (LINE / B_P) / mem, rounded to whole cycles."""
    return round(gamma * mem * b_bytes(rho) / LINE)


def fill(tm: int, tn: int) -> float:
    """Lines LRU sees between two uses of an A-band line, over L1: the A band
    (TM*K*A_P), the C tile of the tile being finished and the C tile of the
    tile being started (each TM*TN*A_P; every k step walks the whole C tile,
    so the new one is fully touched before the band line comes round)."""
    return tm * A_P * (K + 2 * tn) / L1


def b_tile_bytes(tn: int, rho: float) -> int:
    """B column block as it occupies L1: K rows, each padded to a line."""
    return K * max(tn * b_bytes(rho), LINE)


def mem_cliff(tn: int, rho: float) -> float:
    """Fill at which memory-B's A band stops surviving: the B tile also
    passes through L1 between two uses of an A line."""
    return 1 - b_tile_bytes(tn, rho) / L1


def base(rho: float, lam: int) -> Params:
    bp = b_bytes(rho)
    return Params(orientation="weight", m=M, k=K, n=N,
                  small_precision=bp, ratio=A_P // bp, aligned=True,
                  reg_dim=4, mulacc_cost=0,
                  block_size=6, mem_cycles=lam * L1_CYC,
                  l1_size=L1, l1_cycles=L1_CYC, l1_assoc=-1, l2_size=0,
                  write_alloc=True, policy="lru",
                  fifo_capacity=16384, fifo_access=L1_CYC, seed_size=8)


def gamma_star(sp: dict[float, float]) -> float:
    """Break-even gamma: log(speedup) interpolated to 0 along the positive
    gammas (geometric in gamma). inf if FIFO wins at every gamma run."""
    gs = [g for g in GAMMAS if g > 0]
    if sp[gs[0]] < 1:
        return 0.0
    for lo, hi in zip(gs, gs[1:]):
        a, b = math.log(sp[lo]), math.log(sp[hi])
        if a >= 0 > b:
            t = a / (a - b)
            return math.exp(math.log(lo) + t * (math.log(hi) - math.log(lo)))
    return math.inf


def fmt_gamma(g: float) -> str:
    return "inf" if math.isinf(g) else f"{g:.2f}"


CLIFF_SEARCH_FROM = 0.4   # fill below which bumps come from B residency, not A


def measured_cliff(series: dict[int, float]) -> int | None:
    """First TM (with fill >= CLIFF_SEARCH_FROM) at which L1 misses rise by
    more than 50 % over the previous TM step: the A band is reloaded per
    tile column from there on. Below that fill the miss count moves with
    whether the whole B matrix stays resident across tile rows."""
    tms = sorted(series)
    for lo, hi in zip(tms, tms[1:]):
        if fill(hi, TN_FIXED) >= CLIFF_SEARCH_FROM and series[hi] > 1.5 * series[lo]:
            return hi
    return None


def gc_star(gamma: float, mem: int, rho: float) -> str:
    """Break-even generation cost in cycles per element."""
    return "inf" if math.isinf(gamma) else f"{gamma * mem * b_bytes(rho) / LINE:.0f}"


def main() -> None:
    out = out_dir(NAME)

    grid: dict[tuple, Params] = {}
    for rho, lam in product(RHOS, LAMBDAS):
        b = base(rho, lam)
        for tm, tn in product(TMS, TNS):
            grid[(rho, lam, "memory", None, tm, tn)] = replace(
                b, b_source="memory", tile_h=tm, tile_w=tn)
            for g in GAMMAS:
                grid[(rho, lam, "fifo", g, tm, tn)] = replace(
                    b, b_source="fifo", tile_h=tm, tile_w=tn,
                    gen_cost=gc_of(g, b.mem_cycles, rho))
    keys = list(grid)
    res = dict(zip(keys, run_many([grid[k] for k in keys], out / "results.json")))

    # ---- best vs best -------------------------------------------------------
    def best(rho, lam, src, g):
        cells = [(res[k][CYC], k[4], k[5]) for k in keys if k[:4] == (rho, lam, src, g)]
        return min(cells)

    best_mem = {(r, l): best(r, l, "memory", None) for r, l in product(RHOS, LAMBDAS)}
    best_fifo = {(r, l, g): best(r, l, "fifo", g)
                 for r, l, g in product(RHOS, LAMBDAS, GAMMAS)}
    speedup = {(r, l): {g: best_mem[(r, l)][0] / best_fifo[(r, l, g)][0] for g in GAMMAS}
               for r, l in product(RHOS, LAMBDAS)}
    gstar = {k: gamma_star(v) for k, v in speedup.items()}

    # ---- fixed tile ---------------------------------------------------------
    fills = [fill(tm, TN_FIXED) for tm in TMS]

    def series(rho, lam, src, g, stat=CYC):
        return {tm: res[(rho, lam, src, g, tm, TN_FIXED)][stat] for tm in TMS}

    cliffs = {}
    for rho, lam in product(RHOS, LAMBDAS):
        cliffs[(rho, lam, "memory")] = measured_cliff(series(rho, lam, "memory", None, MISS))
        cliffs[(rho, lam, "fifo")] = measured_cliff(series(rho, lam, "fifo", 0, MISS))

    # ---- figures ------------------------------------------------------------
    gpos = {g: i for i, g in enumerate(GAMMAS)}          # categorical gamma axis
    cmap = plt.get_cmap("viridis")
    gcol = {g: cmap(i / (len(GAMMAS) - 1)) for i, g in enumerate(GAMMAS)}

    fig, axes = plt.subplots(1, len(LAMBDAS), figsize=(5 * len(LAMBDAS), 4), sharey=True)
    for ax, lam in zip(axes, LAMBDAS):
        for rho in RHOS:
            ax.plot([gpos[g] for g in GAMMAS], [speedup[(rho, lam)][g] for g in GAMMAS],
                    marker="o", label=f"rho = {rho:g}")
        ax.axhline(1, color="k", lw=0.8, ls="--")
        ax.set_xticks(list(gpos.values()), [f"{g:g}" for g in GAMMAS])
        ax.set_yscale("log")
        ax.set_xlabel("gamma = generate a line of B / fetch it from DRAM")
        ax.set_title(f"lambda = mem / L1 = {lam}")
        ax.grid(alpha=0.3)
    axes[0].set_ylabel("best memory-B cycles / best FIFO cycles")
    axes[0].legend()
    fig.suptitle("FIFO speedup, each side at its best tile (above 1: FIFO wins)")
    fig.tight_layout()
    fig.savefig(out / "speedup_vs_gamma.png", dpi=130)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(5, 4))
    top = 2 * max(g for g in GAMMAS)
    for lam in LAMBDAS:
        ys = [gstar[(rho, lam)] for rho in RHOS]
        ax.plot(RHOS, [min(y, top) for y in ys], marker="o", label=f"lambda = {lam}")
        for rho, y in zip(RHOS, ys):
            if math.isinf(y):
                ax.annotate("> 8", (rho, top), textcoords="offset points",
                            xytext=(0, 4), ha="center", fontsize=8)
    ax.set_xscale("log", base=2)
    ax.set_yscale("log", base=2)
    ax.set_xticks(RHOS, [f"{r:g}" for r in RHOS])
    ax.set_xlabel("rho = B_P / A_P")
    ax.set_ylabel("break-even gamma*")
    ax.set_title("FIFO worth it below the line")
    ax.grid(alpha=0.3, which="both")
    ax.legend()
    fig.tight_layout()
    fig.savefig(out / "breakeven.png", dpi=130)
    plt.close(fig)

    for fname, stat, ylabel, logy in (
            ("cycles_vs_fill.png", CYC, "cycles / MAC", True),
            ("stall_vs_fill.png", STALL, "FIFO stall cycles / total cycles", False)):
        fig, axes = plt.subplots(len(LAMBDAS), len(RHOS),
                                 figsize=(4 * len(RHOS), 3.4 * len(LAMBDAS)),
                                 sharex=True, sharey=True, squeeze=False)
        for (i, lam), (j, rho) in product(enumerate(LAMBDAS), enumerate(RHOS)):
            ax = axes[i][j]
            if stat == CYC:
                m = series(rho, lam, "memory", None)
                ax.plot(fills, [m[tm] / MNK for tm in TMS], color="k", lw=2,
                        label="B from memory")
            for g in GAMMAS:
                f = series(rho, lam, "fifo", g)
                if stat == CYC:
                    ys = [f[tm] / MNK for tm in TMS]
                else:
                    s = series(rho, lam, "fifo", g, STALL)
                    ys = [s[tm] / f[tm] for tm in TMS]
                ax.plot(fills, ys, color=gcol[g], marker=".", ms=4, lw=1,
                        label=f"FIFO gamma = {g:g}")
            ax.axvline(1, color="gray", ls="--", lw=0.8)
            ax.axvline(mem_cliff(TN_FIXED, rho), color="k", ls=":", lw=0.8)
            if logy:
                ax.set_yscale("log")
            ax.grid(alpha=0.3)
            if i == 0:
                ax.set_title(f"rho = {rho:g}")
            if j == 0:
                ax.set_ylabel(f"lambda = {lam}\n{ylabel}")
            if i == len(LAMBDAS) - 1:
                ax.set_xlabel(f"f = TM * A_P * (K + 2 TN) / L1   (TN = {TN_FIXED})")
        axes[0][0].legend(fontsize=7)
        fig.suptitle(f"{ylabel} vs L1 fill at TN = {TN_FIXED}; dashed: FIFO cliff "
                     "f = 1, dotted: memory cliff f = 1 - B tile / L1")
        fig.tight_layout()
        fig.savefig(out / fname, dpi=130)
        plt.close(fig)

    # ---- README -------------------------------------------------------------
    L = []
    L += [f"# {NAME}: is a PRNG-FIFO worth adding, given the device?", "",
          "B-stationary matmul, B either loaded from memory or generated by a "
          "PRNG-FIFO, on the same tile grid. Each side picks its own best tile; "
          "the ratio of the two best cycle counts says whether the FIFO pays "
          "off on this device. A fixed-tile view of the same runs shows where "
          "the win comes from.", "",
          f"run: `.venv/bin/python experiments/rewrite/{NAME}.py`", "",
          "## Parameters", "",
          "| symbol | definition | meaning |", "|---|---|---|",
          "| A_P, B_P | bytes per element of A and of B; C has A's size | A_P = 8 fixed |",
          "| rho | B_P / A_P | precision ratio (slides: T_N*/T_M* = 1/rho). 1, 1/2, 1/4, 1/8 |",
          "| gamma | gc * (64 / B_P) / mem_cycles | time to generate one cache line "
          "of B divided by the time to fetch it from DRAM. 1: generator as slow as "
          "DRAM; 1/4: four times faster. gc = round(gamma * mem * B_P / 64) |",
          "| lambda | mem_cycles / l1_cycles | DRAM latency counted in L1 hits; only "
          "the ratio matters. 45 is mem 180, 100 is mem 400 |",
          "| f | TM * A_P * (K + 2 TN) / L1 | L1 fill: what LRU sees between two "
          "uses of a line of the A row band. The band itself (TM*K*A_P, reused "
          "across tile columns), the C tile of the tile being finished and the C "
          "tile of the tile being started (TM*TN*A_P each; every k step walks the "
          "whole C tile, so the new one is fully touched before the band line comes "
          "round). The FIFO's A band survives iff f <= 1 |",
          "| memory cliff | 1 - K * max(TN*B_P, 64) / L1 | with B from memory the B "
          "column block also passes through L1 between two uses of an A line (K "
          "rows, each at least one line under `--aligned`), so the band survives "
          "only up to this smaller f |", "",
          "Why gamma: in B-stationary both sides bring every B element in once per "
          "tile row, memory at mem/(64/B_P) cycles per element, the FIFO at gc. "
          "gamma is the ratio of the two. If the costs simply added up, break-even "
          "would sit at gamma = 1; the distance from 1 is what the FIFO's overlap "
          "with A loads and its zero L1 footprint buy.", "",
          "## Fixed", "",
          "| | value | why |", "|---|---|---|",
          f"| M, N, K | {M}, {N}, {K} | K = {K} makes an A row {K * A_P // LINE} lines, "
          "so the cliff spans many TM steps |",
          f"| A_P = C_P | {A_P} B | the high-precision side |",
          f"| L1 | {L1 // 1024} KB, fully associative, LRU, no L2 | capacity misses only, "
          "sharp cliff |",
          f"| line | {LINE} B | |",
          f"| l1_cycles | {L1_CYC} | the time unit |",
          f"| fifo_access | {L1_CYC} | a pop costs one L1 hit |",
          "| mulacc | 0 | identical on both sides |",
          "| reg_dim | 4 | |",
          "| write policy | write-back, write-allocate | keeps the C tile resident |",
          "| FIFO capacity | 16384 elements | never the limit |",
          "| seed | 8 B, one read per tile through the cache | |",
          "| layout | `--aligned` | rows and matrix bases on cache-line boundaries |",
          "| dataflow | B-stationary (`-o weight`) | each B element used TM times |", "",
          "## Swept", "",
          "| axis | values | role |", "|---|---|---|",
          f"| TM | {TMS[0]} .. {TMS[-1]} step 4 | minimised over (best vs best); "
          f"x axis as f (fixed tile) |",
          f"| TN | {', '.join(map(str, TNS))} | minimised over (best vs best); "
          f"{TN_FIXED} in the fixed-tile view |",
          f"| rho | {', '.join(f'{r:g}' for r in RHOS)} | B_P = 8, 4, 2, 1 |",
          f"| gamma | {', '.join(f'{g:g}' for g in GAMMAS)} | FIFO runs only |",
          f"| lambda | {', '.join(map(str, LAMBDAS))} | |", "",
          f"{len(keys)} runs, {sum(1 for k in keys if k[2] == 'memory')} of them memory-B.", ""]

    L += ["## Results: best vs best", "",
          "![speedup](speedup_vs_gamma.png)", "", "![breakeven](breakeven.png)", "",
          "Speedup = best memory-B cycles / best FIFO cycles, each side at its own "
          "best (TM, TN). gamma* is where it crosses 1 (log-interpolated between "
          "the gammas run; `inf` means the FIFO still wins at gamma = 8).", "",
          "gc* is the same break-even as a generation cost in cycles per element, "
          "gc* = gamma* * mem * B_P / 64.", "",
          "| rho | lambda | " + " | ".join(f"g={g:g}" for g in GAMMAS) + " | gamma* | gc* |",
          "|---|---|" + "---|" * len(GAMMAS) + "---|---|"]
    for rho, lam in product(RHOS, LAMBDAS):
        sp = speedup[(rho, lam)]
        L.append(f"| {rho:g} | {lam} | " + " | ".join(f"{sp[g]:.2f}" for g in GAMMAS)
                 + f" | {fmt_gamma(gstar[(rho, lam)])} "
                 f"| {gc_star(gstar[(rho, lam)], lam * L1_CYC, rho)} |")
    L += ["", "### Tiles each side picked (TM x TN, cycles/MAC)", "",
          "| rho | lambda | memory | " + " | ".join(f"FIFO g={g:g}" for g in GAMMAS) + " |",
          "|---|---|---|" + "---|" * len(GAMMAS)]
    for rho, lam in product(RHOS, LAMBDAS):
        c, tm, tn = best_mem[(rho, lam)]
        row = [f"{rho:g}", str(lam), f"{tm}x{tn} ({c / MNK:.3f})"]
        for g in GAMMAS:
            c, tm, tn = best_fifo[(rho, lam, g)]
            row.append(f"{tm}x{tn} ({c / MNK:.3f})")
        L.append("| " + " | ".join(row) + " |")

    L += ["", f"## Results: fixed tile, TN = {TN_FIXED}", "",
          "![cycles](cycles_vs_fill.png)", "", "![stalls](stall_vs_fill.png)", "",
          f"One tile row costs {A_P * (K + 2 * TN_FIXED)} B of reuse distance, so "
          f"f = TM / {L1 / (A_P * (K + 2 * TN_FIXED)):.1f}. Predicted cliffs (first "
          "TM past the threshold) against the measured one (first TM with f >= "
          f"{CLIFF_SEARCH_FROM} where L1 misses rise by more than 50 % over the "
          "previous step):", "",
          "| rho | lambda | side | predicted f | predicted TM | measured TM |",
          "|---|---|---|---|---|---|"]
    for rho, lam in product(RHOS, LAMBDAS):
        for side, fc in (("FIFO", 1.0), ("memory", mem_cliff(TN_FIXED, rho))):
            pred_tm = next((tm for tm in TMS if fill(tm, TN_FIXED) > fc), None)
            L.append(f"| {rho:g} | {lam} | {side} | {fc:.3f} | {pred_tm} | "
                     f"{cliffs[(rho, lam, side.lower())]} |")

    sp0 = {k: v[0] for k, v in speedup.items()}
    L += ["", "## Reading the results", "", OBSERVATIONS.format(
        s1_45=sp0[(1, 45)], s1_100=sp0[(1, 100)],
        s8_45=sp0[(0.125, 45)], s8_100=sp0[(0.125, 100)],
        g1_45=fmt_gamma(gstar[(1, 45)]), g1_100=fmt_gamma(gstar[(1, 100)]),
        gc1_45=gc_star(gstar[(1, 45)], 180, 1), gc1_100=gc_star(gstar[(1, 100)], 400, 1),
        g2_45=fmt_gamma(gstar[(0.5, 45)]), g2_100=fmt_gamma(gstar[(0.5, 100)]),
        g4_100=fmt_gamma(gstar[(0.25, 100)]),
    ).strip(), ""]
    (out / "README.md").write_text("\n".join(L))
    print("\n".join(L[L.index("## Results: best vs best"):]))


OBSERVATIONS = """
**The FIFO wins whenever the generator is at least as fast as DRAM, and the
gain is set by rho.** For gamma <= 1 the best-vs-best speedup is flat: the
FIFO's best tile is A-bound (no stalls, see `stall_vs_fill.png` at TM >= 20),
so generation speed doesn't show in the runtime. The flat value is the FIFO's
ceiling on this device: {s1_45:.2f}x at rho = 1 and lambda = 45,
{s1_100:.2f}x at lambda = 100, falling to {s8_45:.2f}x / {s8_100:.2f}x at
rho = 1/8. Two things shrink with rho: the B traffic memory-B pays, and the L1
space B takes away from the A band. At 1-byte B both are small, so there is
little left for the FIFO to remove.

**Break-even is well above gamma = 1.** If costs added up, generating B at
DRAM speed would be a wash. Measured: gamma* = {g1_45} (gc* = {gc1_45}
cycles/element) at rho = 1, lambda = 45, and {g1_100} ({gc1_100}
cycles/element) at lambda = 100; {g2_45} / {g2_100} at rho = 1/2; {g4_100} at
rho = 1/4, lambda = 100; above 8 in the remaining cases. Two reasons. The
FIFO's generation overlaps with the A loads, so it costs nothing until
gc * ceil(M/TM) / M exceeds the A cost per MAC, and the FIFO can grow TM to
amortize (its best tile moves from 48x16 to 96x64 once generation binds). And
in gamma units a line of 1-byte B is 64 elements, so "DRAM speed" is a very
fast generator in absolute terms: gamma = 8 at rho = 1/8, lambda = 45 is only
gc = 22 cycles per element, which at TM = 48 is still below the A cost. So as
rho shrinks the FIFO's gain gets smaller but its tolerance for a slow
generator, measured against DRAM, gets larger. In cycles per element the
break-even moves the other way (gc* column).

**Where the win comes from (fixed tile, TN = 16).** Memory-B steps up at its
cliff and the FIFO at f = 1; between the two the FIFO wins at every gamma run,
because memory is already reloading the A band from DRAM once per tile column
and the FIFO is not. That band is 0.75 <= f < 1 at rho = 1 (B tile 16 KB of
the 64 KB L1) and 0.875 <= f < 1 at rho <= 1/2. Below the memory cliff the FIFO
still wins while it is A-bound; at gamma = 4 and 8 it is generation-bound
there (stall fraction 0.5 to 0.95) and slower than memory. Above f = 1 both
sides pay the per-column A reload and converge; the sawtooth there is
ceil(M/TM): TM = 64 and 96 divide M = 192, TM = 72 leaves a 48-row last tile
row whose band fits again.

**The cliffs land where predicted, in all 16 cases,** once f counts the C
tile twice and the B block as K padded rows. The first version of f (A band
plus one C tile) put the FIFO cliff at TM = 60; it is at 52, because between
two uses of an A-band line the whole C tile of the next tile has already been
walked. In lines: TM * (16 + 2 + 2) <= 1024 gives TM <= 51.2. Memory-B adds
the B block, 256 lines at rho = 1, 128 at rho = 1/2, and still 128 at rho <=
1/4 because 16 elements of 2 or 1 bytes are padded to a full line under
`--aligned`; hence the same memory cliff (TM = 48) for rho = 1/2, 1/4 and 1/8.

**The paper's T_N / T_M = 1/rho does not appear here.** Memory-B's best tile is
48x8 at every rho: the largest TM whose band survives, with the narrowest TN
so the B block displaces as little of the band as possible. The traffic
formula's A_P / T_N term assumes the A tile is fetched once per tile; with
the band resident in L1 across tile columns, A traffic is compulsory and
independent of TN, so TN only acts through the C tile and the B block. The
1/rho shape matters above the cliff, where A really is reloaded per tile
column, and that region is never the optimum.

**Small-TM bumps on the memory side** (rho = 1/8, TM = 8 vs 12) are the whole
B matrix (32 KB at 1 byte) staying resident across tile rows while the band
is small, which is why the cliff search starts at f = 0.4.
"""


if __name__ == "__main__":
    main()
