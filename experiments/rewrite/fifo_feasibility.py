NAME = "fifo_feasibility"

# ---- working point (sources in the README) ----------------------------------
M, K, N = 192, 128, 256
A_P, B_P = 4, 1           # bytes per element: fp32 A and C, int8 B
R = 8                     # register block side; an A block row is R * A_P = 32 B
LINE = 64                 # bytes per cache line
L1 = 32 * 1024            # bytes; fully associative, LRU, no L2
T1 = 5                    # cycles per L1 hit
T_MEM = 200               # cycles per DRAM access
MULACC = 26               # cycles per register block of R^3 MACs
FIFO_BYTES = 2048         # the hardware FIFO
SEED = 8                  # bytes per seed
REG_BYTES = 32            # a 256-bit register
MNK = M * N * K

TMS = tuple(range(8, 97, 8))
TNS = (8, 16, 32, 64, 128, 256)
TILES = tuple(product(TMS, TNS))
DEPTHS = (0, 64, 128, 256, 512, 1024, 2048, 4096, 8192)   # FIFO bytes
BURST_TILES = ((48, 16), (48, 128))
BURST_FACTORS = (0.5, 0.75, 0.9, 1.0, 1.1, 1.25, 1.5, 2.0)

CYC = "Simulation: Total cycles"
STALL = "PrngFifo: stall_cycles"
ACCESSES = "CacheUnit: L1 accesses"
MISSES = "CacheUnit: L1 misses"
POPS = "PrngFifo: pops"

WP = Params(orientation="weight", b_source="fifo", m=M, k=K, n=N,
            small_precision=B_P, ratio=A_P // B_P, aligned=True,
            reg_dim=R, mulacc_cost=MULACC,
            block_size=LINE.bit_length() - 1, mem_cycles=T_MEM,
            l1_size=L1, l1_cycles=T1, l1_assoc=-1, l2_size=0,
            write_alloc=True, policy="lru",
            fifo_capacity=FIFO_BYTES // B_P, gen_cost=0,
            fifo_access=T1, seed_size=SEED)

# ---- figure style -------------------------------------------------------------
