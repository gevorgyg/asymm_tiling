def simulator_issues(cal: dict) -> str:
    """What in these results comes from how the simulator models the machine."""
    tmb = cal["t_mem"]
    sf, sm = cal["res"][fifo(tmb, 0)], cal["res"][memory(tmb)]
    d_hit = (sm[ACCESSES] - sf[ACCESSES]) * T1 / MNK
    d_miss = (sm[MISSES] - sf[MISSES]) * T_MEM / MNK
    d_pop = sf[POPS] * T1 / MNK
    d_tot = cal["alpha_m"][tmb] - cal["alpha_f"][tmb]
    assert abs(d_hit + d_miss - d_pop - d_tot) < 1e-9, "cost split does not add up"
    extra = R - math.ceil(R * R * B_P / REG_BYTES)            # L1 accesses per B block
    over = extra * T1 * (K // R) * (N // R) * tile_rows(tmb[0]) / MNK
    knee = cal["knee"]
    text = f"""
- Only the FIFO runs in parallel with the core. Every cache access stalls the
  core until it completes, so memory-B pays the full {T_MEM} cycles for every
  line of B that misses, one at a time, and DRAM has no bandwidth limit. At
  memory-B's best tile ({tile_str(tmb)}) memory-B costs {d_tot:.3f} cycles per
  MAC more than the FIFO with a free generator: {d_miss:.3f} of it is DRAM
  latency for the misses B adds, {d_hit:.3f} is L1 hits for B's loads, and the
  FIFO's pops give {d_pop:.3f} back. A C7x would stream B with its streaming
  engines, or copy it to L2 SRAM by DMA before it is used, and hide most of
  that latency. So S_max and the break-even here favour the FIFO.
- The FIFO starts empty at every tile (`PrngFifo::load_seed`). Each tile
  begins with a stall of r²·g_c, and lead the generator built in one tile
  can't carry into the next. This is part of the gap between measured and
  predicted speedup near the knee, and one reason wider tiles (fewer tiles)
  win there. The next tile's seed is at a fixed address, so a generator could
  start on it early.
- The seed is read through L1 at the start of every tile. At 32×64, where f is
  exactly 1.00, that one line is enough to push the A band out.
- Registers are r × r blocks for A, B and C alike. An 8×8 block of int8 is 64
  bytes, two 32-byte registers, but memory-B pays {R} L1 accesses for it, one
  per row. At memory-B's best tile that overcharges it by {over:.4f} cycles
  per MAC, {over / cal['alpha_m'][tmb]:.1%} of its cost.
- g_c is a whole number of cycles. Near the knee (g_c ≈ {knee:.0f}) one cycle is
  a {1 / knee:.0%} step, and a generator faster than one element per cycle
  can't be set without scaling every other latency.
- T_K is always K, so the A band is a full row of K elements. With K in the
  thousands, as in real layers, no tile would fit L1. K = {K} keeps the L1
  limit inside the range of T_M swept here.
"""
    return "## Simulator issues these runs expose\n\n" + text.strip()


