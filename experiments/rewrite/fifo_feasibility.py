"""fifo_feasibility: when does a PRNG FIFO beat loading B from memory?

B-stationary matmul at one working point modelled on a 256-bit C7x. B is
either generated by the PRNG FIFO or loaded through L1 from DRAM; A and C
always go through L1. Results are read through two composite parameters:

  gamma = beta / alpha   generation cycles per MAC over the core's own cycles
                         per MAC (alpha: the same tile at g_c = 0)
  f = T_M (K A_P + 2 max(T_N A_P, line)) / L1
                         how full L1 is between two uses of a line of the
                         A band

Four experiments. Each is one function that runs what it needs (cached in
out/fifo_feasibility/results.json), draws its figure and returns its README
section:

  calibration_experiment  FIFO at g_c = 0 and memory-B on all 72 tiles: alpha,
                          and what the max model predicts from it
                          -> calibration.png
  sweep_experiment        FIFO at about 25 generator costs, with a 2 KB FIFO
                          (generator in parallel with the core) and with
                          capacity 0 (generation blocks the core) -> speedup.png
  depth_experiment        FIFO capacity 0 B to 8 KB at the knee and at the
                          break-even, and a finer sweep around the burst at
                          the start of a tile -> depth.png
  collapse_experiment     every run with a generator against gamma, with all
                          model_sweep runs (read from its cache, not re-run)
                          -> collapse.png

run:  .venv/bin/python experiments/rewrite/fifo_feasibility.py
"""

