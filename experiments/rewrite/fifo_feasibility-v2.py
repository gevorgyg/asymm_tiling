def sweep_experiment(cal: dict, out: Path) -> tuple[dict, str]:
    """FIFO at every generator cost of all_gcs, 2 KB and capacity 0, all
    tiles: the FIFO's best tile against memory-B's best, measured and
    predicted."""
    res = run(sweep_params(cal))
    knee, a_m0, g_star = cal["knee"], cal["a_m0"], cal["g_star"]
    gcs = all_gcs(cal)
    x = [gc / knee for gc in gcs]
    picks = [best(res, gc) for gc in gcs]
    meas_par = [a_m0 / v for v, _ in picks]
    meas_blk = [a_m0 / best(res, gc, 0)[0] for gc in gcs]
    pred_par = [a_m0 / predict(cal, gc)[0] for gc in gcs]
    pred_blk = [a_m0 / predict(cal, gc, False)[0] for gc in gcs]
    be_meas = crossing(gcs, meas_par)
    be_blk = crossing(gcs, meas_blk)
    grid = list(np.geomspace(1, gcs[-1], 4000))
    be_blk_pred = crossing(grid, [a_m0 / predict(cal, g, False)[0] for g in grid])
    s_max = a_m0 / cal["a_f0"]

    named = [ts[0] for _, ts in picks]

    gap, gap_gc = max((abs(m / p - 1), gc) for m, p, gc in zip(meas_par, pred_par, gcs))
    below = [(gc, m / p - 1) for gc, m, p in zip(gcs, meas_par, pred_par) if gc < knee]
    i_bad = next(i for i, (gc, d) in enumerate(below) if d <= -0.01)
    held = below[i_bad - 1][0]
    first_drop = below[i_bad:]
    ts = cal["t_star"]
    saving = a_m0 - cal["alpha_f"][ts]
    taller = []
    for gc, t in zip(gcs, named):
        if gc > be_meas and t[0] > cal["t_dag"][0] and tile_str(t) not in taller:
            taller.append(tile_str(t))
    drop_txt = ", ".join(f"{-d:.1%} at γ₀ = {gc / knee:.2f}" for gc, d in first_drop[:3])
    reading = f"""
Below the knee the generator is hidden and the speedup stays close to S_max =
{s_max:.3f}. It is within 1% of the prediction up to γ₀ = {held / knee:.2f}
and then starts to fall below it ({drop_txt}), because the tiles are not
alike (see the worked example under the composites). Near the knee the
measurement is furthest below the prediction, {gap:.1%} at γ₀ =
{gap_gc / knee:.2f}.

The measured break-even is g_c = {be_meas:.1f} (γ₀ = {be_meas / knee:.2f}),
below the {g_star:.1f} the max model predicts. No run is faster than
max(α, β), so the predicted break-even is an upper bound for any FIFO depth;
the depth section shows how close a deeper FIFO gets. Past the break-even the
FIFO moves to taller tiles ({', then '.join(taller[:2])}), but their α is
already above memory-B's best, so the speedup stays below 1 and the max model
follows the measurements closely again.

With capacity 0 the generator blocks the core, so the time is α + β by
construction, and the break-even, g_c = {be_blk:.1f}, is where β
equals what loading B costs at the FIFO's best tile: α_m* − α_f =
{saving:.3f} cycles per MAC, times the {M / tile_rows(ts[0]):.0f} MACs each
element serves, {saving * M / tile_rows(ts[0]):.1f} cycles per element.
Generating in parallel with the core tolerates a generator
{be_meas / be_blk:.1f} times slower.

In bytes, the measured break-even is one int8 element every {be_meas:.0f}
cycles, about {1e3 / be_meas:.0f} MB/s at 1 GHz. Like the knee, that figure
scales with α, which at this working point is mostly access latency paid one
access at a time (see the sensitivity section).
"""
    L = ["## Generator sweep", "",
         "| | max model | measured |", "|---|---|---|",
         f"| break-even, 2 KB FIFO | g_c = {g_star:.1f} (γ₀ = {g_star / knee:.2f}) | "
         f"g_c = {be_meas:.1f} (γ₀ = {be_meas / knee:.2f}) |",
         f"| break-even, capacity 0 | g_c = {be_blk_pred:.1f} | g_c = {be_blk:.1f} "
         "(the same by construction) |",
         f"| largest gap between measured and predicted speedup, 2 KB | | "
         f"{gap:.1%} at g_c = {gap_gc} (γ₀ = {gap_gc / knee:.2f}) |", "",
         reading.strip(), "",
         "Every point. The g_c from "
         f"{fine_gcs(cal)[0]} to {fine_gcs(cal)[-1]} are a finer grid around the "
         "break-even; tied tiles are within 0.5% of the best:", "",
         "| g_c | γ₀ | S max model | S measured, 2 KB | best tile, 2 KB | "
         "S max model, capacity 0 | S measured, capacity 0 |",
         "|---|---|---|---|---|---|---|"]
    for gc, pp, mp, (_, tl), pb, mb in zip(gcs, pred_par, meas_par, picks, pred_blk, meas_blk):
        L.append(f"| {gc} | {gc / knee:.2f} | {pp:.3f} | {mp:.3f} | {tiles_str(tl)} | "
                 f"{pb:.3f} | {mb:.3f} |")
    stats = {"be_meas": be_meas, "be_blk": be_blk, "gap": gap, "gap_gc": gap_gc}
    return res | {"_stats": stats}, "\n".join(L)


def depth_experiment(cal: dict, out: Path) -> str:
    """FIFO capacity from 0 to 32 KB at the generator costs of depth_gcs, best
    tile at each capacity, plus a finer sweep around the burst at the start of
    a tile for two tiles."""
    knee, a_m0 = cal["knee"], cal["a_m0"]
    gcs = depth_gcs(cal)
    knee_gc, be_gc = round(knee), round(cal["g_star"])
    checks = [(t, gc, [max(1, round(burst(t, gc) * f)) for f in BURST_FACTORS])
              for t in BURST_TILES for gc in (knee_gc, be_gc)]
    res = run(depth_params(cal)
              + [replace(fifo(t, gc), fifo_capacity=c) for t, gc, caps in checks for c in caps])
    curves = {gc: [best(res, gc, d) for d in DEPTHS] for gc in gcs}
    unl = {gc: curves[gc][-1][0] for gc in gcs}

    def smallest(gc: int, ok) -> int | None:
        return next((d for d, (v, _) in zip(DEPTHS, curves[gc]) if ok(v)), None)

    within = {gc: smallest(gc, lambda v, gc=gc: v <= 1.01 * unl[gc]) for gc in gcs}
    beats = {gc: smallest(gc, lambda v: v < a_m0) for gc in gcs}


    def flat_from(t: tuple[int, int], gc: int, caps: list[int]) -> float:
        # the smallest multiple of the burst from which time stays within
        # 0.5% of its value at twice the burst
        vals = [cpm(res[replace(fifo(t, gc), fifo_capacity=c)]) for c in caps]
        return next(f for i, f in enumerate(BURST_FACTORS)
                    if all(v <= 1.005 * vals[-1] for v in vals[i:]))

    flat = {(t, gc): flat_from(t, gc, caps) for t, gc, caps in checks}
    hi = [(t, gc) for t, gc, _ in checks if beta(gc, t[0]) / cal["alpha_f"][t] >= 1]
    lo = [(t, gc) for t, gc, _ in checks if beta(gc, t[0]) / cal["alpha_f"][t] < 1]
    one_pop = max(gc for gc in gcs if within[gc] == R * R * B_P)
    g82 = min(gcs, key=lambda g: abs(g / knee - 0.82))
    bound = predict(cal, be_gc)[0]
    deep = min(curves[be_gc][DEPTHS.index(d)][0] for d in DEPTHS if d >= 4096)
    two_k = DEPTHS.index(FIFO_BYTES)

    def size(d: int) -> str:
        return f"{d // 1024} KB" if d >= 1024 else f"{d} bytes"

    def at(keys: list) -> str:
        items = [f"{flat[k]:.2f} times the burst for {tile_str(k[0])} at g_c = {k[1]}" for k in keys]
        return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]

    gap_2k = curves[knee_gc][two_k][0] / unl[knee_gc] - 1
    two_k_text = (f"is {gap_2k:.1%} slower than one that never fills" if gap_2k >= 0.0005
                  else "is as fast as one that never fills")
    reading = f"""
How deep the FIFO has to be depends on γ₀. Up to γ₀ = {one_pop / knee:.2f}
(g_c = {one_pop}) one pop, 64 bytes, is within 1% of a FIFO that never fills:
the generator refills a block long before the core asks for the next one.
Closer to the knee the need grows: {size(within[g82])} at γ₀ =
{g82 / knee:.2f}, {size(within[knee_gc])} at the knee, where the 2 KB FIFO
{two_k_text}, and {size(within[be_gc])} at g_c = {be_gc}. At g_c = {be_gc}, the max model's break-even, the 2 KB FIFO loses to
memory-B and {size(beats[be_gc])} wins; 4 KB or more comes within
{deep / bound - 1:.1%} of the max model's bound there, max(α, β) =
{bound:.4f}. Past the break-even no capacity beats memory-B, and the depth
needed for 1% goes up and down with the tile the FIFO picks.

The depth needed near the knee is set by the start of each tile. The FIFO
starts empty there, and in the first k step the core reads every line of the
C tile for the first time: the loop loads C before it accumulates into it,
and each of those read misses blocks the core for t_mem. While the core
waits, the generator makes T_M · ⌈T_N·A_P / line⌉ · (t_mem + t_1) / g_c
elements. A smaller FIFO fills up and the generator idles, and later in the
tile, where the core is faster than the generator, the core stalls for the
lead it could not bank. The table at the end runs capacities from half to
twice that burst for tiles {and_list(tile_str(t) for t in BURST_TILES)}. Where the tile's γ is 1
or more, the time stops falling (stays within 0.5% of its value at twice the
burst) at {at(hi)}. Where γ is below 1 it stops earlier, at {at(lo)}, because
the generator is faster than the core for the rest of the tile and part of
the lead is never needed. A kernel computing C = A·B would zero its
accumulators instead of loading C, and a core with misses in flight would not
wait for each line in turn, so this burst comes from the simulator's model
(see simulator issues).
"""
    L = ["## FIFO depth", "",
         "| g_c | γ₀ | FIFO that never fills: cycles per MAC, tile | smallest capacity "
         "within 1% of it | smallest capacity faster than memory-B | 2 KB FIFO |",
         "|---|---|---|---|---|---|"]
    for gc in gcs:
        v, tl = curves[gc][-1]
        L.append(f"| {gc} | {gc / knee:.2f} | {v:.4f}, {tiles_str(tl)} | {within[gc]} B | "
                 f"{f'{beats[gc]} B' if beats[gc] is not None else 'none'} | "
                 f"{curves[gc][two_k][0]:.4f} |")
    L += ["", reading.strip(), "",
          f"Every capacity at the knee (g_c = {knee_gc}) and at the max model's "
          f"break-even (g_c = {be_gc}): cycles per MAC, best tile, share of time "
          f"stalled. Memory-B's best is {a_m0:.4f}.", "",
          "| capacity, bytes | " + " | ".join(f"g_c = {gc}" for gc in (knee_gc, be_gc)) + " |",
          "|---|---|---|"]
    for i, d in enumerate(DEPTHS):
        row = [str(d)]
        for gc in (knee_gc, be_gc):
            c, tl = curves[gc][i]
            st = res[fifo(tl[0], gc, d)]
            row.append(f"{c:.4f}, {tiles_str(tl, 1)}, {st[STALL] / st[CYC]:.0%}")
        L.append("| " + " | ".join(row) + " |")
    L += ["", "Fixed tile, capacity as a multiple of the burst (cycles per MAC):", "",
          "| tile | g_c | γ of the tile | burst, elements | "
          + " | ".join(f"× {f:g}" for f in BURST_FACTORS) + " |",
          "|---|---|---|---|" + "---|" * len(BURST_FACTORS)]
    for t, gc, caps in checks:
        vals = [cpm(res[replace(fifo(t, gc), fifo_capacity=c)]) for c in caps]
        L.append(f"| {tile_str(t)} | {gc} | {beta(gc, t[0]) / cal['alpha_f'][t]:.2f} | "
                 f"{burst(t, gc):.0f} | " + " | ".join(f"{v:.4f}" for v in vals) + " |")
    return "\n".join(L)


def tiles_experiment(cal: dict, res: dict, out: Path) -> str:
    """The FIFO against memory-B on the same tile, in cycles. Graphs:
    tile_cycles.png, cycles per MAC against g_c, one panel per tile of
    FIGURE_TMS x FIGURE_TNS;
    tile_speedup.png, the speedup of every tile with a free generator;
    tile_breakeven.png, the largest g_c at which the FIFO still wins;
    tile_speedup_gc.png, the speedup against g_c for six tiles;
    tile_breakeven_blocking.png, the same limit for a generator that blocks
    the core; tile_depth.png, cycles per MAC against FIFO capacity, one panel
    per tile of the cycles figure."""
    af, am = cal["alpha_f"], cal["alpha_m"]
    gcs = all_gcs(cal)

    def breakeven(t: tuple[int, int], depth: int, mem: tuple[int, int] | None = None) -> float:
        """Largest g_c at which B from the FIFO on tile t beats B from memory
        on tile mem (t itself unless given)."""
        ys = [am[mem or t] / cpm(res[fifo(t, gc, depth)]) for gc in gcs]
        assert ys[0] >= 1, f"the FIFO loses at g_c = {gcs[0]} on {t}"
        g = crossing(gcs, ys)
        return math.inf if g is None else g

    speed = {t: am[t] / af[t] for t in TILES}
    be = {t: breakeven(t, FIFO_BYTES) for t in TILES}
    be0 = {t: breakeven(t, 0) for t in TILES}
    # the rule: g_c / T_M per MAC, exactly g_c ceil(M / T_M) / M
    rule = {t: am[t] * M / tile_rows(t[0]) for t in TILES}
    rule0 = {t: (am[t] - af[t]) * M / tile_rows(t[0]) for t in TILES}
    a, b = PAIR
    switch = breakeven(b, FIFO_BYTES, mem=a)

    cycle_tiles = list(product(FIGURE_TMS, FIGURE_TNS))
    plot_tile_cycles(gcs, {t: [cpm(res[fifo(t, gc)]) for gc in gcs] for t in cycle_tiles},
                     {t: am[t] for t in cycle_tiles}, out / "tile_cycles.png")
    plot_tile_map(speed, lambda v: f"{v:.2f}", "memory-B cycles / FIFO cycles at $g_c$ = 0",
                  out / "tile_speedup.png")
    plot_tile_map(be, lambda v: f"{v:.0f}", "largest $g_c$ at which the FIFO wins [cycles]",
                  out / "tile_breakeven.png", log=True)
    plot_tile_speedup_lines(gcs, {t: [am[t] / cpm(res[fifo(t, gc)]) for gc in gcs]
                                  for t in LINE_TILES}, out / "tile_speedup_gc.png")
    plot_tile_map(be0, lambda v: f"{v:.1f}",
                  "largest $g_c$ at which a blocking generator wins [cycles]",
                  out / "tile_breakeven_blocking.png", log=True)
    depth_gc = {t: sorted({max(1, round(f * be[t])) for f in DEPTH_FRACTIONS})
                for t in cycle_tiles}
    dres = run([fifo(t, gc, d) for t in cycle_tiles for gc in depth_gc[t] for d in DEPTHS])
