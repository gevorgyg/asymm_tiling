# ---- runs -------------------------------------------------------------------
def fifo(tile: tuple[int, int], gc: int, depth: int = FIFO_BYTES) -> Params:
    tm, tn = tile
    return replace(WP, tile_h=tm, tile_w=tn, gen_cost=gc,
                   fifo_capacity=depth // B_P)


def memory(tile: tuple[int, int]) -> Params:
    tm, tn = tile
    return replace(WP, b_source="memory", tile_h=tm, tile_w=tn)


def run(params: list[Params]) -> dict[Params, dict[str, float]]:
    """Stats of every run, cached in out/fifo_feasibility-v2/results.json."""
    stats = run_many(params, out_dir(NAME) / "results.json")
    return dict(zip(params, stats))


def cpm(stats: dict[str, float]) -> float:
    """Cycles per MAC."""
    return stats[CYC] / MNK


def tile_str(t: tuple[int, int]) -> str:
    return f"{t[0]}×{t[1]}"


def tiles_str(ts: list[tuple[int, int]], most: int = 2) -> str:
    """The first tile, and the tiles tied with it."""
    if len(ts) == 1:
        return tile_str(ts[0])
    rest = ", ".join(tile_str(t) for t in ts[1:most + 1])
    more = f" and {len(ts) - most - 1} more" if len(ts) > most + 1 else ""
    return f"{tile_str(ts[0])} (tied: {rest}{more})"


# ---- model ------------------------------------------------------------------
def tile_rows(tm: int) -> int:
    return -(-M // tm)


def beta(gc: float, tm: int) -> float:
    """Generation cycles per MAC: B is generated once per tile row."""
    return gc * tile_rows(tm) / M


def fill(tm: int, tn: int, b_source: str = "fifo") -> float:
    """f: what has to stay in L1 for a whole tile row, over L1. The A band and
    two C tiles (a C tile row narrower than a line still takes the line), and
    the seed line for the FIFO or the B block (K rows of at least one line)
    for memory-B."""
    keep = tm * (K * A_P + 2 * max(tn * A_P, LINE))
    keep += LINE if b_source == "fifo" else K * max(tn * B_P, LINE)
    return keep / L1


def fill_tile(tm: int, tn: int) -> float:
    """The tile limit: between two k steps the core walks the whole C tile and
    two k-columns of A. Past 1, C is read from DRAM again inside the tile."""
    return tm * (max(tn * A_P, LINE) + 2 * LINE) / L1


def largest_tm(limit) -> dict[int, int | None]:
    """Largest T_M of the grid with limit(T_M, T_N) <= 1, per T_N."""
    return {tn: max((tm for tm in TMS if limit(tm, tn) <= 1), default=None)
            for tn in TNS}


def and_list(items) -> str:
    """'a', 'a and b', 'a, b and c'."""
    items = [str(i) for i in items]
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def tile_limit_jumps(alpha: dict) -> dict[int, float]:
    """For every T_N with several tile columns and its tile limit inside the
    grid: the step in alpha past the tile limit, when it is the largest step
    of the column."""
    lim_t = largest_tm(fill_tile)
    out = {}
    for tn in TNS:
        if N // tn < 2 or lim_t[tn] >= TMS[-1]:
            continue
        steps = {tm: alpha[(tm, tn)] / alpha[(tm - 8, tn)] for tm in TMS[1:]}
        if max(steps, key=steps.get) == lim_t[tn] + 8:
            out[tn] = steps[lim_t[tn] + 8]
    return out


def burst(tile: tuple[int, int], gc: int) -> float:
    """Elements generated while the core takes the C tile's first misses at the
    start of a tile: T_M rows of ceil(T_N A_P / line) lines, each an L1 access
    and a DRAM access."""
    tm, tn = tile
    return tm * -(-tn * A_P // LINE) * (T_MEM + T1) / gc


def ranked(times: dict) -> list[tuple[int, int]]:
    """The tiles within TIE of the lowest time, fewest tile rows first, then
    by time. The first one is the tile we name."""
    lo = min(times.values())
    near = [t for t, v in times.items() if v <= (1 + TIE) * lo]
    return sorted(near, key=lambda t: (tile_rows(t[0]), times[t], t))


def derive(af: dict, am: dict) -> dict:
    """What the max model takes from a calibration (alpha of every tile, FIFO
    and memory-B): the best tiles, the knee, T_M dagger and the break-even."""
    a_f0, a_m0 = min(af.values()), min(am.values())
    near = [t for t in TILES if af[t] <= (1 + TIE) * a_f0]
    # knee: the largest g_c at which a tile within TIE of alpha_f0 still hides
    # the generator, alpha * M / ceil(M / T_M)
    knee, knee_tile = max((af[t] * M / tile_rows(t[0]), t) for t in near)
    # T_M dagger: the tile with the fewest tile rows whose alpha still beats
    # memory-B's best; past g_star even that tile is slower than memory-B
    t_dag = max((t for t in TILES if af[t] < a_m0),
                key=lambda t: (M / tile_rows(t[0]), -af[t]))
    g_star = a_m0 * M / tile_rows(t_dag[0])
    return {"alpha_f": af, "alpha_m": am, "a_f0": a_f0, "ties_f": ranked(af),
            "t_star": ranked(af)[0], "a_m0": a_m0, "ties_m": ranked(am),
            "t_mem": ranked(am)[0], "knee": knee, "knee_tile": knee_tile,
            "t_dag": t_dag, "g_star": g_star}


def calibrate() -> dict:
    """alpha of every tile, FIFO at g_c = 0 and memory-B, and what the max
    model predicts from it."""
    res = run([fifo(t, 0) for t in TILES] + [memory(t) for t in TILES])
    af = {t: cpm(res[fifo(t, 0)]) for t in TILES}
    am = {t: cpm(res[memory(t)]) for t in TILES}
    return derive(af, am) | {"res": res}


def predict(cal: dict, gc: float, parallel: bool = True,
            tiles=TILES) -> tuple[float, tuple[int, int]]:
    """Lowest cycles per MAC over the tiles, from the calibration alone:
    max(alpha, beta) for a generator in parallel with the core, alpha + beta
    for one that blocks it. Returns (cycles per MAC, tile)."""
    af = cal["alpha_f"]
    if parallel:
        return min((max(af[t], beta(gc, t[0])), t) for t in tiles)
    return min((af[t] + beta(gc, t[0]), t) for t in tiles)


def sweep_gcs(cal: dict) -> list[int]:
    """Generator costs on a log scale: gamma_0 from 1/16 to 16 (or to four
    times the predicted break-even), plus the knee and the break-even."""
    knee, g_star = cal["knee"], cal["g_star"]
    top = max(16.0, 4 * g_star / knee)
    steps = range(-12, math.ceil(3 * math.log2(top)) + 1)
    gcs = {round(knee * 2 ** (i / 3)) for i in steps}
    gcs |= {round(knee), round(g_star)}
    return sorted(g for g in gcs if g > 0)


def fine_gcs(cal: dict) -> list[int]:
    """Every whole g_c from 0.85 of the knee to just past the predicted
    break-even, so the measured break-even needs no long interpolation."""
    return list(range(round(0.85 * cal["knee"]), round(1.05 * cal["g_star"]) + 1))


def all_gcs(cal: dict) -> list[int]:
    return sorted(set(sweep_gcs(cal)) | set(fine_gcs(cal)))


def sweep_params(cal: dict) -> list[Params]:
    return [fifo(t, gc, d) for gc in all_gcs(cal)
            for d in (FIFO_BYTES, 0) for t in TILES]


def depth_gcs(cal: dict) -> list[int]:
    """The sweep's generator costs from gamma_0 = 0.2 to 2.6."""
    return [gc for gc in sweep_gcs(cal) if 0.2 <= gc / cal["knee"] <= 2.6]


def depth_params(cal: dict) -> list[Params]:
    return [fifo(t, gc, d) for gc in depth_gcs(cal) for d in DEPTHS for t in TILES]


def best(res: dict, gc: int, depth: int = FIFO_BYTES,
         tiles=TILES) -> tuple[float, list[tuple[int, int]]]:
    """Measured: the lowest cycles per MAC over the tiles, and the tiles within
    TIE of it (the one with the fewest tile rows first)."""
    times = {t: cpm(res[fifo(t, gc, depth)]) for t in tiles}
    return min(times.values()), ranked(times)


def crossing(xs: list[float], ys: list[float]) -> float | None:
    """First x where ys drops below 1, interpolated (log x, linear y)."""
    for x0, y0, x1, y1 in zip(xs, ys, xs[1:], ys[1:]):
        if y0 >= 1 > y1:
            t = (y0 - 1) / (y0 - y1)
            return math.exp(math.log(x0) + t * (math.log(x1) - math.log(x0)))
    return None


def tile_account(tile: tuple[int, int], gc: int, depth: int = FIFO_BYTES) -> dict:
    """Core cycles of the first tile of a tile row and of each later tile, from
    runs with N = T_N and N = 2 T_N at g_c = 0, and the time that summing
    max(core, generation) tile by tile predicts. The core waits r^2 g_c for
    the first B block of a tile; once the generator is the bottleneck a tile
    takes the generation time plus the work after the last pop. Only for
    tiles that divide M and N."""
    tm, tn = tile
    one, two = replace(fifo(tile, 0), n=tn), replace(fifo(tile, 0), n=2 * tn)
    r = run([one, two, fifo(tile, 0), fifo(tile, gc, depth)])
    rows, cols = tile_rows(tm), N // tn
    first = r[one][CYC] / rows
    later = (r[two][CYC] - r[one][CYC]) / rows
    gen = K * tn * gc
    wait = R * R * gc
    tail = -(-tm // R) * (3 * R * T1 + MULACC) + T1
    total = rows * (max(first + wait, gen + tail)
                    + (cols - 1) * max(later + wait, gen + tail))
    a, b = cpm(r[fifo(tile, 0)]), beta(gc, tm)
    return {"first": first, "later": later, "gen": gen, "per_tile": total,
            "measured": r[fifo(tile, gc, depth)][CYC], "max_model": max(a, b) * MNK,
            "stall": r[fifo(tile, gc, depth)][STALL], "alpha": a, "beta": b}


def memory_b_python(job: tuple[tuple[int, int], bool]) -> int:
    """Total cycles of memory-B for one tile, computed in Python: the loop of
    MultiUnit::reg_weight_mul over a fully associative LRU L1 with no L2, the
    working point's latencies and the aligned layout. With packed=False it
    must give build/sim's number exactly (checked in sensitivity_experiment);
    packed=True stores each r x r block of B in one line, in the order the
    core reads the blocks, which build/sim can't do."""
    (tm, tn), packed = job

    def stride(width: int, elem: int) -> int:
        return -(-width * elem // LINE) * LINE

    sa, sb, sc = stride(K, A_P), stride(N, B_P), stride(N, A_P)
    a0, b0 = 0, M * sa
    c0 = b0 + K * sb
    lru: OrderedDict[int, None] = OrderedDict()
    cyc = 0

    def touch(line: int) -> None:
        nonlocal cyc
        cyc += T1
        if line in lru:
            lru.move_to_end(line)
        else:
            cyc += T_MEM
            lru[line] = None
            if len(lru) > L1 // LINE:
                lru.popitem(last=False)

    def block(base: int, stride_: int, elem: int, h: int, w: int, r: int, c: int) -> None:
        # MultiUnit::calculate_addr: every line each row of the block spans
        width = min(R, w - c * R) * elem
        for i in range(min(R, h - r * R)):
            start = base + (r * R + i) * stride_ + c * R * elem
            for line in range(start // LINE, (start + width - 1) // LINE + 1):
                touch(line)

    for row in range(tile_rows(tm)):
        th = min(tm, M - row * tm)
        ta = a0 + row * tm * sa
        for col in range(-(-N // tn)):
            tw = min(tn, N - col * tn)
            tb, tc = b0 + col * tn * B_P, c0 + row * tm * sc + col * tn * A_P
            for k in range(K // R):
                for c in range(-(-tw // R)):
                    if packed:
                        touch((b0 + (k * (N // R) + col * tn // R + c) * R * R * B_P) // LINE)
                    else:
                        block(tb, sb, B_P, K, tw, k, c)
                    for r in range(-(-th // R)):
                        block(ta, sa, A_P, th, K, r, k)
                        block(tc, sc, A_P, th, tw, r, c)
                        cyc += MULACC
                        block(tc, sc, A_P, th, tw, r, c)
    return cyc


def model_sweep_cache() -> dict:
    return json.loads((OUT / "model_sweep" / "results.json").read_text())


def model_sweep_check(n: int = 24, seed: int = 1) -> dict:
    """model_sweep's cache was written by an older build. Re-simulate n of its
    runs, picked at random, with the current build and count exact matches."""
    cached = model_sweep_cache()
    keys = random.Random(seed).sample(sorted(cached["results"]), n)
    params = [Params(**json.loads(k)) for k in keys]
    now = run(params)
    same = sum(all(now[p].get(name) == v for name, v in cached["results"][k].items())
               for p, k in zip(params, keys))
    return {"old": cached["sim_sha"][:7], "new": sim_sha()[:7], "same": same, "n": n}


def model_sweep_alpha() -> dict:
    """alpha of every model_sweep tile at g_c = 0, by tile column:
    {(L1, M, K, N, T_N): {T_M: alpha}}."""
    cols: dict = defaultdict(dict)
    for key, s in model_sweep_cache()["results"].items():
        p = json.loads(key)
        assert (p["small_precision"], p["ratio"], p["block_size"], p["seed_size"]) == (4, 1, 6, 8)
        if p["gen_cost"] == 0:
            cols[(p["l1_size"], p["m"], p["k"], p["n"], p["tile_w"])][p["tile_h"]] = \
                s[CYC] / (p["m"] * p["n"] * p["k"])
    return cols


def model_sweep_fill(l1: int, k: int, n: int, tm: int, tn: int) -> float:
    """f for model_sweep's device: 4-byte A, B and C, 64-byte lines, an 8-byte
    seed (one line). model_sweep doesn't pad rows to lines, so unless the rows
    of C and of a C tile both span whole lines, a C tile row can straddle one
    line more than its width needs; f counts that line."""
    whole = (n * 4) % LINE == 0 and (tn * 4) % LINE == 0
    c_lines = -(-tn * 4 // LINE) + (0 if whole else 1)
    return (tm * (k * 4 + 2 * c_lines * LINE) + LINE) / l1


