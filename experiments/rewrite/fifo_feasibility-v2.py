def model_sweep_runs() -> list[tuple[float, float, bool, float]]:
    """Every model_sweep run with g_c > 0: (gamma, cycles per MAC / alpha,
    last tile row shorter than T_M / 2, time over the max taken per tile row).
    Read from model_sweep's cache."""
    alpha, runs = {}, []
    for key, s in model_sweep_cache()["results"].items():
        p = json.loads(key)
        gc = p.pop("gen_cost")
        rest = json.dumps(p, sort_keys=True)
        t = s[CYC] / (p["m"] * p["n"] * p["k"])
        if gc == 0:
            alpha[rest] = t
        else:
            runs.append((rest, gc, p["m"], p["tile_h"], t))
    out = []
    for rest, gc, m, tm, t in runs:
        if rest not in alpha:
            continue
        a = alpha[rest]
        rows = -(-m // tm)
        heights = [min(tm, m - i * tm) for i in range(rows)]
        per_row = sum(max(a * h, gc) for h in heights) / m
        out.append((gc * rows / m / a, t / a, heights[-1] < tm / 2, t / per_row))
    return out


def collapse_points(cal: dict, res: dict) -> dict[str, list[tuple[float, float]]]:
    """(gamma, cycles per MAC / alpha) of every run with g_c > 0."""
    pts = {"model_sweep": [(g, y) for g, y, _, _ in model_sweep_runs()],
           "parallel": [], "blocking": []}
    for gc in all_gcs(cal):
        for tile in TILES:
            a = cal["alpha_f"][tile]
            g = beta(gc, tile[0]) / a
            pts["parallel"].append((g, cpm(res[fifo(tile, gc)]) / a))
            pts["blocking"].append((g, cpm(res[fifo(tile, gc, 0)]) / a))
    return pts


