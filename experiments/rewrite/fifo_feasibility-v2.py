def sensitivity_experiment(cal: dict, res: dict, out: Path) -> tuple[dict, str]:
    """The calibration again with one part of the model changed at a time, and
    two changes to memory-B computed from this working point's runs. No
    figure."""
    rows = {}
    for name, kw in SCENARIOS.items():
        r = run([replace(fifo(t, 0), **kw) for t in TILES]
                + [replace(memory(t), **kw) for t in TILES])
        rows[name] = derive({t: cpm(r[replace(fifo(t, 0), **kw)]) for t in TILES},
                            {t: cpm(r[replace(memory(t), **kw)]) for t in TILES})
    base = cal["res"]
    # memory-B reads every line of B once per tile row at least; free those
    # misses, and keep B's lines in L1
    hidden = "memory-B with B's own misses free (B still takes room in L1)"
    b_lines = K * N * B_P // LINE
    rows[hidden] = derive(cal["alpha_f"], {
        t: cal["alpha_m"][t] - b_lines * tile_rows(t[0]) * T_MEM / MNK for t in TILES})
    # free every miss memory-B takes beyond the FIFO's: B's, and the A misses
    # its room in L1 causes (for the text)
    no_extra = derive(cal["alpha_f"], {
        t: cal["alpha_m"][t] - (base[memory(t)][MISSES] - base[fifo(t, 0)][MISSES]) * T_MEM / MNK
        for t in TILES})
    with ProcessPoolExecutor() as pool:
        plain = dict(zip(TILES, pool.map(memory_b_python, [(t, False) for t in TILES])))
        packed = dict(zip(TILES, pool.map(memory_b_python, [(t, True) for t in TILES])))
    bad = [t for t in TILES if plain[t] != base[memory(t)][CYC]]
    assert not bad, f"the Python model of memory-B differs from build/sim at {bad}"
    pk = "memory-B with B packed in r × r blocks (Python model)"
    rows[pk] = derive(cal["alpha_f"], {t: packed[t] / MNK for t in TILES})

    # these three keep this working point's FIFO side, so the measured 2 KB
    # sweep gives their break-even too
    gcs = all_gcs(cal)
    fifo_best = [best(res, gc)[0] for gc in gcs]
    measured = {name: crossing(gcs, [rows[name]["a_m0"] / v for v in fifo_best])
                for name in ("the working point", hidden, pk)}

    lines = ["| change | α_f0, tile | α_m*, tile | S_max | knee g_c | T_M† | break-even g_c*, "
             "max model (γ₀) | break-even, measured 2 KB (γ₀) |",
             "|---|---|---|---|---|---|---|---|"]
    for name, d in rows.items():
        m = measured.get(name)
        lines.append(
            f"| {name} | {d['a_f0']:.4f}, {tile_str(d['t_star'])} | {d['a_m0']:.4f}, "
            f"{tiles_str(d['ties_m'], 1)} | {d['a_m0'] / d['a_f0']:.3f} | {d['knee']:.1f} | "
            f"{d['t_dag'][0]} | {d['g_star']:.1f} ({d['g_star'] / d['knee']:.2f}) | "
            + (f"{m:.1f} ({m / d['knee']:.2f})" if m else "not run") + " |")

    def s(name: str) -> float:
        return rows[name]["a_m0"] / rows[name]["a_f0"]

    w = rows["the working point"]
    l2a, l2b, l2c = (rows[k] for k in list(SCENARIOS)[3:6])
    fast = rows["L1 hit and pop in 1 cycle"]
    reading = f"""
Every number in the sections above holds for this model of the machine: no
L2, every access paying its full latency before the next one starts, and B
stored row by row. The table repeats the calibration with one of those
changed at a time. The last two rows keep this working point's runs and
change only memory-B: one frees B's own misses, the other stores B in packed
blocks.

Without DRAM latency (t_mem = 0) S_max is {s('no DRAM latency (t_mem = 0)'):.3f},
so almost all of the FIFO's lead at this working point is DRAM latency, and
most of that is B's own. With only B's own misses free, memory-B's best is
{rows[hidden]['a_m0']:.4f} at {tiles_str(rows[hidden]['ties_m'], 1)},
S_max = {s(hidden):.3f}, and against the measured 2 KB sweep the FIFO breaks
even at g_c ≈ {measured[hidden]:.1f}, below the knee. That row still keeps
B's lines in L1, which caps memory-B at T_M = {rows[hidden]['t_mem'][0]}. If B
also stayed out of L1, as it does when the C7x's streaming engines read it
past L1D, memory-B could use the FIFO's tall tiles; freeing every miss
memory-B takes beyond the FIFO's gives S_max = {no_extra['a_m0'] / no_extra['a_f0']:.3f}.
Storing B in packed 8×8 blocks of one
line each gives memory-B fewer L1 accesses and a B block of K·T_N bytes
instead of K lines, so it can use the same tall tiles as the FIFO: its best is
{rows[pk]['a_m0']:.4f} at {tiles_str(rows[pk]['ties_m'], 1)}, S_max drops to
{s(pk):.3f} and the measured break-even to g_c ≈ {measured[pk]:.1f}, about the
knee. build/sim has no packed layout, so this row comes from a Python copy of
its loop (`memory_b_python`), which reproduces build/sim's memory-B cycles
exactly on all {len(TILES)} tiles of the row-major layout.

An L2 that holds the whole problem, as the TDA4VM's 512 KB L2 would (SPRADC1
§2.8.1), turns B's repeated misses into L2 hits. S_max drops to
{l2a['a_m0'] / l2a['a_f0']:.3f} with a 6-cycle L2 (0.03 of t_mem, the ratio in
SPRADC1 Table 3-1) and to {l2b['a_m0'] / l2b['a_f0']:.3f} with 15 cycles. The
predicted break-even moves out to {l2a['g_star'] / l2a['knee']:.1f} times the
knee all the same: memory-B's best α is now above the α of tiles {l2a['t_dag'][0]}
rows tall, so the FIFO can use those, generate B for {tile_rows(l2a['t_dag'][0])}
tile rows instead of {tile_rows(w['t_dag'][0])}, and keep its small lead up to
a much slower generator. With only the 64 KB the SDK sets up
as L2 cache, S_max is {l2c['a_m0'] / l2c['a_f0']:.3f}.

With 1-cycle L1 hits and pops, α_f0 shrinks to {fast['a_f0']:.3f}, S_max rises
to {s('L1 hit and pop in 1 cycle'):.2f} and the knee falls from
{w['knee']:.1f} to {fast['knee']:.1f}. Every absolute g_c above (knee,
break-even, the MB/s figure) assumes {T1}-cycle accesses taken one at a time.

So the FIFO's lead at this working point, {s('the working point') - 1:.0%}
while the generator is hidden, depends on the model. With B's own misses
hidden or B packed it is {s(hidden) - 1:.0%} to {s(pk) - 1:.0%}, and it lasts
only up to about the knee.
"""
    text = "\n".join(["## How much the answer depends on the model", "",
                      *lines, "", reading.strip()])
    return rows | {"_measured": measured, "_hidden": hidden, "_packed": pk}, text


def simulator_issues(cal: dict, sens: dict) -> str:
    """What in these results comes from how the simulator models the machine."""
    tmb, ts = cal["t_mem"], cal["t_star"]
    sf, sm = cal["res"][fifo(tmb, 0)], cal["res"][memory(tmb)]
    d_hit = (sm[ACCESSES] - sf[ACCESSES]) * T1 / MNK
    d_miss = (sm[MISSES] - sf[MISSES]) * T_MEM / MNK
    d_pop = sf[POPS] * T1 / MNK
    d_tot = cal["alpha_m"][tmb] - cal["alpha_f"][tmb]
    assert abs(d_hit + d_miss - d_pop - d_tot) < 1e-9, "cost split does not add up"
    extra = int(sm[MISSES] - sf[MISSES])
    b_lines = K * N * B_P // LINE
    b_miss = b_lines * tile_rows(tmb[0])
    split = cal["split"]
    a = cal["alpha_f"][ts]
    per_block = cal["res"][fifo(ts, 0)][ACCESSES] / (MNK / R ** 3)
    hidden, pk = sens["_hidden"], sens["_packed"]
    fast = sens["L1 hit and pop in 1 cycle"]
    text = f"""
- Every cache access stalls the core until it completes, misses are taken one
  at a time, and nothing streams or prefetches B. At memory-B's best tile
  ({tile_str(tmb)}) memory-B costs {d_tot:.4f} cycles per MAC more than the
  FIFO with a free generator. {d_miss:.4f} of it is DRAM latency for the
  {extra:,} misses it takes beyond the FIFO's: B's {b_lines} lines, missed
  again in each of the {tile_rows(tmb[0])} tile rows ({b_miss:,}), less
  {b_miss - extra} misses the FIFO takes on its seeds. {d_hit:.4f} is L1 hits
  for B's loads, and the FIFO's pops give {d_pop:.4f} back. A C7x streams B
  with its streaming engines, or copies it into L2 SRAM by DMA before it is
  used. With B's own misses free, S_max is
  {sens[hidden]['a_m0'] / sens[hidden]['a_f0']:.3f} and the FIFO breaks even
  below the knee (previous section). A and C misses block the core the same
  way: they are {split['DRAM misses'] / a:.0%} of α_f0.
- L1 hits are charged one after another too: {split['L1 hits'] / a:.0%} of α_f0
  is L1 hit latency, {per_block:.0f} accesses of {T1} cycles per {R ** 3} MACs.
  The C7x's two load/store units pipeline their loads (SPRADC1 Fig. 2-5).
  With 1-cycle hits the knee falls from {cal['knee']:.1f} to {fast['knee']:.1f}.
- C is read before it is computed. In the first k step the loop loads every
  block of the C tile (`load_into_reg(c, ...)` in `MultiUnit::reg_weight_mul`),
  so each tile starts with a read miss on every line of its C tile, taken one
  at a time. A kernel computing C = A·B would zero its accumulators. This
  burst is what sets the FIFO depth needed near the knee.
- The FIFO starts empty at every tile (`PrngFifo::load_seed`). Each tile waits
  r²·g_c for its first B block, and the lead the generator builds while the
  core is slow in one tile can't carry into the next. Near γ = 1 this is most
  of the time above max(α, β) (worked example in the composites section). The
  next tile's seed is at a fixed address, so a generator could start on it
  early.
- B is stored row by row. An 8×8 block of int8 B then spans {R} lines and
  takes {R} L1 accesses, and a B tile narrower than a line still takes K whole
  lines of L1, which caps memory-B at T_M = {max(t[0] for t in cal['ties_m'])}.
  Deployed int8 weights are usually packed in the order the kernel reads
  them; the previous section estimates that case
  (S_max {sens[pk]['a_m0'] / sens[pk]['a_f0']:.3f}).
- There is no L2, so every L1 miss goes to DRAM. The TDA4VM's C7x has 512 KB
  of L2, which would hold this whole problem; the previous section shows what
  that changes.
- The seed is read through L1 at the start of every tile. At 32×64 that one
  line is what pushes the A band out: f is {fill(32, 64):.3f} with it and
  {fill(32, 64) - LINE / L1:.3f} without.
- g_c is a whole number of cycles. Near the knee one cycle is a
  {1 / cal['knee']:.0%} step, and a generator faster than one element per cycle
  can't be set without scaling every other latency.
- T_K is always K, so the A band is a full row of K elements. With K in the
  thousands, as in real layers, no tile would fit L1. K = {K} keeps the L1
  limit inside the range of T_M swept here.
"""
    return "## Simulator issues these runs expose\n\n" + text.strip()


