"""Model-validity sweep with FIFO-generated B (B-stationary).

Same shape as paper-model-validity, but B is not stored: a per-tile seed is
read from memory and the tile is generated by the PRNG-FIFO device. Cost
parity is enforced so that bringing one A element from DRAM and generating one
B element cost the same: with a 64 B line and 8 B elements there are 8
elements per line, so per-element DRAM cost is MEM/8 = 160/8 = 20 cycles,
matched by PRNG_FIFO_GEN_COST = 20. A and B share precision (8 B).

Fix the C-tile aspect at the predicted optimum (T_N/T_M = 4) and grow the
tile; plot the six metric views, an "associativity excess" (8-way L1 traffic
/ fully-assoc L1 traffic, = 1 when associativity is free), and the FIFO
generation/stall load, all against log2(C-tile bytes / L1 bytes).

Contrast with the C-stationary companion: B-stationary generates each B
subtile once and reuses it across the M stream, so FIFO generations should be
far lower — at the cost of streaming C (read-modify-written across k) through
L1 instead of holding it resident. The budget axis (C-tile / L1) is kept for
one-to-one comparability even though C is not the resident matrix here.
"""

import math
from pathlib import Path

from experiments.harness import (
    Cell, Flags, METRICS, describe_changes, lineplot, plot_metric_family,
    run_grid_dual, workspace_root, write_report,
)

EXPERIMENT_DIR = Path(__file__).resolve().parent

M, N, K = 128, 512, 64
PREC = 8                 # A and B share precision
LINE = 64
L1 = 4096                # small L1 so the budget axis reaches log2 = 7
GEN_COST = 20            # = MEM_ACCESS_CYCLES / (LINE / PREC) = 160 / 8

BASE_OVERRIDES: dict[str, object] = {
    "A_HEIGHT_DIM": M, "A_WIDTH_DIM": K, "B_WIDTH_DIM": N,
    "A_PRECISION_BYTES": PREC, "B_PRECISION_BYTES": PREC,
    "L1_SIZE_BYTES": L1, "L1_LINE_SIZE_BYTES": LINE,
    "L2_SIZE_BYTES": 4 * L1, "L2_LINE_SIZE_BYTES": LINE,
    "L2_ACCESS_CYCLES": 14,
    "MEM_ACCESS_CYCLES": GEN_COST * (LINE // PREC),   # 160: parity with the FIFO
    "PRNG_FIFO_GEN_COST": GEN_COST,
    "PRNG_FIFO_CAPACITY": 64,
    "PRNG_FIFO_SEED_BYTES": 8,
    "TILE_K": K,
}

# aspect 4 throughout; C-tile bytes = T_M*T_N*8 → log2(bytes / 4K L1) = -3..7
TILES = [(4, 16), (8, 32), (16, 64), (32, 128), (64, 256), (128, 512)]
REGIMES = [
    ("fully-assoc", {"L1_ASSOC": L1 // LINE, "L2_ASSOC": (4 * L1) // LINE}),
    ("8-way",       {"L1_ASSOC": 8, "L2_ASSOC": 8}),
]

STATIONARY = "B"
BASE_NAME = "fifo_validity"
TITLE = "Model validity, FIFO B (B-stationary)"


def _l1_traffic(m) -> float:
    return m.l1.bytes_in + m.l1.bytes_out


def run() -> None:
    base = (workspace_root() / "default.config").read_text()
    flags = Flags(b_source="prng_fifo", stationary=STATIONARY, three_d_reg=True)

    records: list[dict] = []
    for regime, regime_over in REGIMES:
        print(f"\n--- {regime} ---")
        for tm, tn in TILES:
            duals = run_grid_dual(
                experiment_dir=EXPERIMENT_DIR,
                base_config_text=base,
                base_overrides={**BASE_OVERRIDES, **regime_over,
                                "TILE_M": tm, "TILE_N": tn},
                flags=flags,
            )
            d = duals[0]
            records.append({
                "regime": regime, "tm": tm, "tn": tn,
                "budget": math.log2(tm * tn * PREC / L1), "d": d,
            })

    caption = describe_changes(
        {k: v for k, v in BASE_OVERRIDES.items() if k != "TILE_K"}, base,
        extras={"TILE_K": K, "aspect": "T_N/T_M = 4", "B": "FIFO, gen=fetch cost"},
    )

    # 1) six metric views vs budget, breakdown marker at C-tile = L1 (budget 0)
    cells = [Cell(x=r["budget"], series=r["regime"],
                  traffic=r["d"].traffic, cycles=r["d"].cycles)
             for r in records]
    plot_metric_family(
        cells, out_dir=EXPERIMENT_DIR, base_name=BASE_NAME,
        title=TITLE, caption=caption,
        xlabel="log₂(C-tile bytes / L1 bytes)",
        ref_vlines={"C tile = L1": 0.0},
    )

    # 2) associativity excess = 8-way L1 traffic / fully-assoc L1 traffic
    by_tile = {}
    for r in records:
        by_tile.setdefault((r["tm"], r["tn"]), {})[r["regime"]] = r
    excess = sorted(
        (math.log2(tm * tn * PREC / L1),
         _l1_traffic(v["8-way"]["d"].traffic) / _l1_traffic(v["fully-assoc"]["d"].traffic))
        for (tm, tn), v in by_tile.items() if "8-way" in v and "fully-assoc" in v
    )
    lineplot(
        {"8-way / fully-assoc L1 traffic": excess},
        out_path=EXPERIMENT_DIR / "assoc_excess.png",
        hlines={"associativity free (excess = 1)": 1.0},
        ref_vlines={"C tile = L1": 0.0},
        xlabel="log₂(C-tile bytes / L1 bytes)", ylabel="L1 traffic ratio",
        title=f"Associativity excess, FIFO B (B-stationary)\n{caption}",
    )

    # 3) FIFO load: generations and stall cycles vs budget
    gens = {r["regime"]: [] for r in records}
    stalls = {r["regime"]: [] for r in records}
    for r in records:
        fifo = r["d"].traffic.prng_fifo
        gens[r["regime"]].append((r["budget"], fifo.generates if fifo else 0))
        stalls[r["regime"]].append((r["budget"], fifo.stall_cycles if fifo else 0))
    lineplot(
        {f"{k} generations": sorted(v) for k, v in gens.items()},
        out_path=EXPERIMENT_DIR / "fifo_generations.png",
        ref_vlines={"C tile = L1": 0.0},
        xlabel="log₂(C-tile bytes / L1 bytes)", ylabel="B elements generated",
        title=f"FIFO B generations (B-stationary)\n{caption}",
    )

    lines = [f"Non-default config: {caption}\n",
             "B is FIFO-generated; per-element generation cost equals A's "
             "per-element DRAM cost (both 20 cycles). A and B share 8 B "
             "precision. Seed = 8 B per B tile.\n",
             "![assoc excess](assoc_excess.png)\n",
             "![fifo generations](fifo_generations.png)\n"]
    for k in METRICS:
        lines.append(f"\n![{k}]({BASE_NAME}_{k}.png)")
    write_report(EXPERIMENT_DIR / "README.md", TITLE, ["\n".join(lines)])
